MAX_ELLIPSIS_GAP = 2000


def star_page_at(raw: str, offset: int) -> Optional[str]:
    """The star page in force at a raw offset: the label of the last star-pagination span before it."""
    page = None
    for m in STAR_PAGE_RE.finditer(raw, 0, offset):
        page = m.group(1)
    return page


def anchor(raw: str, quote: str, max_gap: int = MAX_ELLIPSIS_GAP) -> Dict:
    """Anchor one quotation in raw source text. Returns status anchored or anchor_failed with details."""
    # Bluebook ellipses are spaced periods (". . ."); the core splits on "..." or the ellipsis character.
    quote = re.sub(r"\s*\.\s\.\s\.(?:\s\.)?\s*", " ... ", quote).strip()
    doc = Document(raw)
    anchors, failure, warnings = anchor_quote(doc, quote, max_gap)
    if not anchors:
        # An opening alteration ("[a] wrongdoer" quoted as "A wrongdoer") or a leading capital changed for the
        # memo's sentence: match from the second word and say so.
        words = quote.split()
        rest = " ".join(words[1:])
        if len(words) > 8 and "..." not in quote:
            a2, _f2, w2 = anchor_quote(doc, rest, max_gap)
            if a2:
                anchors = a2
                warnings = w2 + [{"code": "first_word_unmatched",
                                  "detail": f"matched from the second word; check the first word '{words[0]}' against the source"}]
    if anchors:
        first = anchors[0]
        return {"status": "anchored", "start": first.start, "end": anchors[-1].end, "method": first.match,
                "segments": [{"start": a.start, "end": a.end} for a in anchors],
                "page": star_page_at(raw, first.start), "warnings": warnings}
    return {"status": "anchor_failed", "reason": failure.reason if failure else "not_found",
            "hint": failure.hint if failure else None, "warnings": warnings}


def entry_text(matter: Path, entry: Dict) -> Optional[str]:
    texts = []
    for rel in [entry.get("local_path"), *(entry.get("files") or [])]:
        if rel and (matter / rel).is_file() and rel not in [t[0] for t in texts]:
            texts.append((rel, read_document(matter / rel)))
    return "\n".join(t for _r, t in texts) if texts else None


def anchor_for_entry(matter: Path, entry: Dict, quote: str) -> Dict:
    """Anchor a quotation against a ledger entry: its saved source, or for a reported secondary source the
    quotations the user brought back (docs/05-secondary-sources.md section 4)."""
    if entry.get("type") == "secondary":
        if entry.get("status") != "reported":
            return {"status": "anchor_failed", "reason": "secondary_not_reported", "hint": None, "warnings": []}
        quotes = [q.get("text", "") for q in (entry.get("report") or {}).get("quotes") or []]
        result = anchor("\n\n".join(quotes), quote) if quotes else {"status": "anchor_failed", "reason": "no_reported_quotes",
                                                                       "hint": None, "warnings": []}
        result["against"] = "secondary_report"
        return result
    raw = entry_text(matter, entry)
    if raw is None:
        return {"status": "anchor_failed", "reason": "source_not_saved", "hint": None, "warnings": []}
    result = anchor(raw, quote)
    result["against"] = entry.get("local_path")
    return result


def main(argv: Optional[List[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    matter, entry_id, quote = Path(args[0]), args[1], args[2]
    ledger = json.loads((matter / "authorities.json").read_text(encoding="utf-8"))
    entry = next((e for e in ledger["authorities"] if e["id"] == entry_id), None)
    if entry is None:
        print(json.dumps({"status": "anchor_failed", "reason": "no_ledger_entry"}))
        return 1
    result = anchor_for_entry(matter, entry, quote)
    print(json.dumps(result, ensure_ascii=False))
    return 0 if result["status"] == "anchored" else 1


if __name__ == "__main__":
    sys.exit(main())
